const fs = require('fs');
const path = require('path');

const pkgPath = path.resolve(__dirname, '../package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));

// Format GMT+7: ddmmyyhh
const now = new Date();
const utc = now.getTime() + now.getTimezoneOffset() * 60000;
const gmt7 = new Date(utc + 7 * 3600000);

const dd = String(gmt7.getDate()).padStart(2, '0');
const mm = String(gmt7.getMonth() + 1).padStart(2, '0');
const yy = String(gmt7.getFullYear()).slice(-2);
const hh = String(gmt7.getHours()).padStart(2, '0');
const buildStamp = `${dd}${mm}${yy}${hh}`;

const version = pkg.version || '0.3.22';
const versionLabel = `v${version} · ${buildStamp}`;

const content = `// Auto-generated by scripts/inject-build-version.js during build step (PRD D5 v0.3.22)
export const APP_VERSION = '${version}';
export const BUILD_STAMP = '${buildStamp}';
export const BUILD_TIME_GMT7 = '${gmt7.toISOString().replace('T', ' ').slice(0, 19)} (GMT+7)';
export const VERSION_LABEL = '${versionLabel}';
`;

const outPath = path.resolve(__dirname, '../src/core/buildInfo.ts');
fs.writeFileSync(outPath, content, 'utf8');
console.log(`[inject-build-version] Injected ${versionLabel} to ${outPath}`);
